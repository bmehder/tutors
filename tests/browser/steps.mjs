import assert from 'node:assert/strict'

const firstDate = () => new Date(Date.now() + 10 * 86400000).toISOString().slice(0, 10)
const visible = locator => locator.waitFor({ state: 'visible' })

async function chooseSchedule(page, { tutor, time, skip = false, zone, blockedTime }) {
  const planner = page.locator('#family-planner')
  await visible(planner.getByRole('combobox', { name: 'Tutor', exact: true }))
  await planner.getByRole('combobox', { name: 'Tutor', exact: true }).selectOption(tutor)
  if (zone) {
    await planner.getByRole('button', { name: 'Change time zone', exact: true }).click()
    await planner.getByLabel('Search a city or time zone', { exact: true }).fill('Amsterdam')
    await planner.getByRole('button', { name: 'Europe/Amsterdam', exact: true }).click()
  }
  await planner.getByLabel('First weekly session', { exact: true }).fill(firstDate())
  if (blockedTime) assert.equal(await planner.getByRole('button', { name: blockedTime }).first().isDisabled(), true, 'Another family’s confirmed time must be unavailable')
  await planner.getByRole('button', { name: time }).first().click()
  await visible(planner.getByText('Your weekly routine is ready to save.', { exact: true }))
  if (skip) {
    const before = await planner.getByRole('button', { name: 'Skip this week', exact: true }).count()
    await planner.getByRole('button', { name: 'Skip this week', exact: true }).first().click()
    await visible(planner.getByText(/Replacement added at the end:/))
    assert.equal(await planner.getByRole('button', { name: 'Skip this week', exact: true }).count(), before)
  }
  await planner.getByRole('button', { name: 'Save schedule & continue', exact: true }).click()
}

async function contact(page, familyName, phone) {
  const planner = page.locator('#family-planner')
  await planner.getByRole('button', { name: 'Next: contact details', exact: true }).click()
  await planner.getByLabel('Contact name', { exact: true }).fill(familyName)
  await planner.getByLabel('Email', { exact: true }).fill('browser-parent@example.test')
  await planner.getByRole('button', { name: 'Next: payment', exact: true }).click()
  await visible(planner.getByRole('heading', { name: 'Contact details', exact: true }))
  await planner.getByLabel('Phone number', { exact: true }).pressSequentially(phone)
  const entered = await planner.getByLabel('Phone number', { exact: true }).inputValue()
  assert.equal(entered, phone.startsWith('+') ? phone : '(555) 867-5309')
  await planner.getByRole('button', { name: 'Next: payment', exact: true }).click()
  await visible(planner.getByRole('button', { name: /^Continue to Stripe/ }))
  await visible(planner.getByText('Packages are non-refundable, except where required by law.', { exact: true }))
  assert.equal(await planner.getByRole('link', { name: 'Booking & refund policy', exact: true }).getAttribute('href'), '/booking-policy')
  assert.equal(await planner.getByRole('link', { name: 'Privacy policy', exact: true }).getAttribute('href'), '/privacy')
  assert.equal(await planner.getByRole('link', { name: 'Booking & refund policy', exact: true }).getAttribute('target'), '_blank')
  assert.equal(await planner.getByRole('link', { name: 'Privacy policy', exact: true }).getAttribute('target'), '_blank')
}

async function pay(page, { decline = false } = {}) {
  await page.getByRole('button', { name: /^Continue to Stripe/ }).click()
  await page.waitForURL(/\/__test-checkout\//)
  if (decline) {
    await page.getByLabel('Card number', { exact: true }).fill('4000000000000002')
    await page.getByRole('button', { name: 'Pay test order', exact: true }).click()
    await visible(page.getByRole('heading', { name: 'Payment declined', exact: true }))
    await page.getByRole('link', { name: 'Try again', exact: true }).click()
  }
  await page.getByLabel('Card number', { exact: true }).fill('4242424242424242')
  await page.getByRole('button', { name: 'Pay test order', exact: true }).click()
  await page.waitForURL(/\/checkout\/stripe\?session_id=/)
  await visible(page.getByRole('heading', { name: 'Booking confirmed', exact: true }))
}

export async function run({ page, desktop, browser, origin, directory, db, schema, env, monitor, noOverflow, capture }) {
  let planner = page.locator('#family-planner')
  await planner.getByRole('button', { name: /^5 hours/ }).click()
  await planner.getByRole('button', { name: 'Next: choose students', exact: true }).click()
  await planner.getByRole('button', { name: 'Next: allocate hours', exact: true }).click()
  await planner.getByLabel('Name', { exact: true }).fill('Browser Emma')
  await planner.getByRole('combobox', { name: 'Subject', exact: true }).selectOption({ label: 'Biology' })
  await planner.getByRole('button', { name: 'Next: choose schedules', exact: true }).click()
  await chooseSchedule(page, { tutor: 'heather-barrieau', time: /9:00 AM/, skip: true })
  await visible(planner.getByRole('heading', { name: 'One family. All planned together.', exact: true }))
  const skippedDate = new Intl.DateTimeFormat('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' }).format(new Date(firstDate() + 'T12:00:00Z'))
  assert.ok(!(await planner.getByText(/^Weekly routine ·/).innerText()).includes(skippedDate), 'Review must show the first actual session after skipping the original start')
  await noOverflow(page, 'Desktop family review')
  await capture(page, 'desktop-review')
  await contact(page, 'Browser Desktop Family', '5558675309')

  // A transient checkout error must leave a usable retry button and the same request identity.
  const attempts = []
  let failOnce = true
  await page.route('**/api/reservations', async route => {
    attempts.push(route.request().postDataJSON())
    if (failOnce) { failOnce = false; await route.fulfill({ status: 503, json: { error: 'Temporary test interruption. Please retry.' } }) }
    else await route.continue()
  })
  await planner.getByRole('button', { name: /^Continue to Stripe/ }).click()
  await visible(planner.getByRole('alert').filter({ hasText: 'Temporary test interruption' }))
  await pay(page, { decline: true })
  assert.equal(attempts.length, 2)
  assert.equal(attempts[0].requestId, attempts[1].requestId)
  await page.unroute('**/api/reservations')
  const order = (await db.query(`SELECT * FROM ${schema}.booking_reservations WHERE label='Browser Desktop Family'`)).rows[0]
  assert.ok(order.confirmed_at)
  assert.equal(order.subtotal_cents, 30000)
  const rows = (await db.query(`SELECT lower(slot) AS start FROM ${schema}.booking_sessions WHERE reservation_id=$1 ORDER BY lower(slot)`, [order.id])).rows
  assert.equal(rows.length, 5)
  const expectedSkipped = firstDate()
  assert.ok(rows[0].start.toISOString().slice(0, 10) > expectedSkipped, 'Skipped first week must move the first booked date forward')
  assert.match(await page.locator('main').innerText(), /Package total \$300/)
  await page.getByText('Customer email', { exact: true }).click()
  await page.getByText('Admin email', { exact: true }).click()
  assert.match(await page.locator('main').innerText(), /Test meeting room/)
  const emails = await db.query(`SELECT recipient,body,sent_at FROM ${schema}.outgoing_emails WHERE reservation_id=$1`, [order.id])
  assert.ok(emails.rows.length >= 2)
  assert.ok(emails.rows.every(email => email.sent_at === null))
  const customerAndAdmin = emails.rows.filter(email => ['browser-parent@example.test', 'admin@mychristiantutors.com'].includes(email.recipient))
  assert.equal(customerAndAdmin.length, 2)
  assert.ok(customerAndAdmin.every(email => email.body.includes('Test meeting room')))
  await noOverflow(page, 'Desktop confirmation')
  await capture(page, 'desktop-confirmation')
  await page.evaluate(() => { window.__printCalls = 0; window.print = () => { window.__printCalls++ } })
  await page.getByRole('button', { name: 'Print details', exact: true }).click()
  assert.equal(await page.evaluate(() => window.__printCalls), 1)
  await page.emulateMedia({ media: 'print' })
  assert.equal(await page.getByRole('button', { name: 'Print details', exact: true }).isVisible(), false)
  await page.pdf({ path: directory + '/desktop-order.pdf', format: 'A4', printBackground: true })
  await page.emulateMedia({ media: 'screen' })
  assert.equal(await page.getByRole('link', { name: 'Contact support', exact: true }).getAttribute('href'), '/#contact')
  const countBefore = emails.rows.length
  await page.reload()
  assert.equal((await db.query(`SELECT count(*)::int AS count FROM ${schema}.outgoing_emails WHERE reservation_id=$1`, [order.id])).rows[0].count, countBefore)
  console.log('PASS — desktop booking, phone mask, skip/replacement, retry, declined payment, webhook confirmation, email previews and print output')

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, timezoneId: 'Europe/London' })
  const phone = await mobile.newPage()
  monitor(phone)
  await phone.goto(origin)
  await phone.locator('#family-planner[aria-busy="false"]').waitFor()
  await phone.getByRole('button', { name: 'Open navigation menu', exact: true }).click()
  await visible(phone.getByRole('navigation', { name: 'Mobile navigation' }))
  await phone.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: 'Plan tutoring', exact: true }).click()
  assert.equal(await phone.getByRole('navigation', { name: 'Mobile navigation' }).isVisible(), false)
  planner = phone.locator('#family-planner')
  await planner.getByRole('button', { name: /^10 hours/ }).click()
  await planner.getByRole('button', { name: 'Next: choose students', exact: true }).click()
  await planner.getByRole('combobox', { name: 'Students', exact: true }).selectOption('2')
  await planner.getByRole('button', { name: 'Next: allocate hours', exact: true }).click()
  const emma = planner.getByRole('group', { name: 'Student 1', exact: true })
  const luke = planner.getByRole('group', { name: 'Student 2', exact: true })
  await emma.getByLabel('Name', { exact: true }).fill('Mobile Emma')
  await luke.getByLabel('Name', { exact: true }).fill('Mobile Luke')
  await emma.getByRole('button', { name: 'Remove subject', exact: true }).click()
  await emma.getByRole('button', { name: 'Add a subject', exact: true }).click()
  await emma.getByRole('combobox', { name: 'Subject', exact: true }).selectOption('Biology')
  await emma.getByRole('combobox', { name: 'Subject hours', exact: true }).selectOption('3')
  await visible(emma.getByText('2 remaining hours — add a subject below.', { exact: true }))
  await emma.getByRole('button', { name: 'Add another subject', exact: true }).click()
  await emma.getByRole('combobox', { name: 'Subject', exact: true }).nth(1).selectOption('Chemistry')
  await luke.getByRole('combobox', { name: 'Subject', exact: true }).selectOption('Algebra 1')
  await visible(planner.getByText('All 10 package hours are assigned.', { exact: true }))
  await noOverflow(phone, 'Mobile allocation')
  await capture(phone, 'mobile-allocation')
  await planner.getByRole('button', { name: 'Next: choose schedules', exact: true }).click()
  await chooseSchedule(phone, { tutor: 'heather-barrieau', time: /4:00 PM/, zone: 'Europe/Amsterdam', blockedTime: /3:00 PM/ })
  await chooseSchedule(phone, { tutor: 'chris-leingang', time: /5:00 PM/ })
  await chooseSchedule(phone, { tutor: 'melissa-lopez', time: /4:00 PM/ })
  await visible(planner.getByRole('heading', { name: 'One family. All planned together.', exact: true }))
  assert.match(await planner.innerText(), /Amsterdam time/)
  assert.doesNotMatch(await planner.innerText(), /GMT|Eastern/)
  await noOverflow(phone, 'Mobile family review')
  await capture(phone, 'mobile-review')
  await contact(phone, 'Browser Mobile Family', '+442079460958')
  await pay(phone)
  await noOverflow(phone, 'Mobile confirmation')
  await capture(phone, 'mobile-confirmation')
  const mobileOrder = (await db.query(`SELECT * FROM ${schema}.booking_reservations WHERE label='Browser Mobile Family'`)).rows[0]
  assert.ok(mobileOrder.confirmed_at)
  assert.equal(mobileOrder.subtotal_cents, 55000)
  assert.equal(mobileOrder.display_time_zone, 'Europe/Amsterdam')
  assert.equal((await db.query(`SELECT count(*)::int AS count FROM ${schema}.booking_sessions WHERE reservation_id=$1`, [mobileOrder.id])).rows[0].count, 10)
  console.log('PASS — mobile navigation, empty subject editing, multi-student/multi-subject allocation, Amsterdam times and 10-session checkout')

  const admin = await desktop.newPage()
  monitor(admin)
  await admin.goto(origin + '/admin')
  await admin.getByLabel('Email', { exact: true }).fill(env.BOOKING_ADMIN_EMAIL)
  await admin.getByLabel('Password', { exact: true }).fill(env.BOOKING_ADMIN_PASSWORD)
  await admin.getByRole('button', { name: 'Sign in', exact: true }).click()
  await visible(admin.getByRole('navigation', { name: 'Admin navigation' }))
  await admin.getByRole('navigation', { name: 'Admin navigation' }).getByRole('button', { name: 'Bookings', exact: true }).click()
  const desktopSummary = admin.locator('summary').filter({ hasText: /Browser Desktop Family\s*Order #/ })
  await visible(desktopSummary)
  await visible(admin.locator('summary').filter({ hasText: /Browser Mobile Family\s*Order #/ }))
  assert.match(await admin.locator('body').innerText(), /Paid \$300\.00/)
  assert.match(await admin.locator('body').innerText(), /Paid \$550\.00/)
  await noOverflow(admin, 'Desktop admin bookings')
  await capture(admin, 'admin-bookings')
  await desktopSummary.click()
  const bookingPanel = desktopSummary.locator('..')
  const sessionPanel = bookingPanel.locator('details').first()
  await sessionPanel.locator(':scope > summary').click()
  const sessionForm = sessionPanel.locator('form').first()
  const replacement = sessionForm.getByRole('combobox', { name: 'Tutor', exact: true })
  assert.equal(await replacement.locator('option[value="chris-leingang"]').count(), 0, 'Tutors without the subject must not be offered')
  const firstSession = (await db.query(`SELECT id,tutor_id FROM ${schema}.booking_sessions WHERE reservation_id=$1 ORDER BY lower(slot) LIMIT 1`, [order.id])).rows[0]
  await replacement.selectOption('melissa-lopez')
  await sessionForm.getByRole('combobox', { name: 'Time', exact: true }).selectOption('00:00')
  await sessionForm.getByRole('button', { name: 'Save session', exact: true }).click()
  await visible(sessionForm.getByRole('alert').filter({ hasText: 'does not offer that time' }))
  assert.equal((await db.query(`SELECT tutor_id FROM ${schema}.booking_sessions WHERE id=$1`, [firstSession.id])).rows[0].tutor_id, firstSession.tutor_id)
  await capture(admin, 'admin-invalid-reschedule')
  await sessionForm.getByRole('combobox', { name: 'Time', exact: true }).selectOption('09:00')
  await sessionForm.getByRole('button', { name: 'Save session', exact: true }).click()
  await visible(admin.getByText('Saved.', { exact: true }))
  assert.equal((await db.query(`SELECT tutor_id FROM ${schema}.booking_sessions WHERE id=$1`, [firstSession.id])).rows[0].tutor_id, 'melissa-lopez')
  console.log('PASS — admin filters tutors by subject, explains an unavailable time without losing the order, and saves a valid tutor change')
  await admin.getByRole('navigation', { name: 'Admin navigation' }).getByRole('button', { name: 'Reports', exact: true }).click()
  await visible(admin.getByRole('heading', { name: 'Reports', exact: true }))
  await capture(admin, 'admin-reports')
  console.log('PASS — authenticated admin lists both paid orders with correct package totals and exposes reports')
  await admin.getByRole('navigation', { name: 'Admin navigation' }).getByRole('button', { name: 'Operations', exact: true }).click()
  await visible(admin.getByRole('heading', { name: 'Operations', exact: true }))
  await visible(admin.getByText('Customer and admin email: paused', { exact: true }))
  await visible(admin.getByText('Tutor email: paused — tutor inquiries go to admin', { exact: true }))
  await noOverflow(admin, 'Desktop operations')
  await capture(admin, 'admin-operations')
  const workerRequests = []
  admin.on('request', request => { if (request.url().includes('/api/deliver-emails')) workerRequests.push(request.method()) })
  const refreshed = admin.waitForResponse(response => response.url().endsWith('/admin') && response.request().method() === 'GET')
  await admin.getByRole('button', { name: 'Refresh status', exact: true }).click()
  await refreshed
  await visible(admin.getByText('Status updated.', { exact: true }))
  assert.deepEqual(workerRequests, [], 'Viewing/refreshing operations must not invoke the sending worker')
  await admin.setViewportSize({ width: 390, height: 844 })
  await noOverflow(admin, 'Phone operations')
  await capture(admin, 'admin-operations-mobile')
  console.log('PASS — private operations view and refresh work on desktop/phone without invoking email delivery')

  for (const [path, heading] of [['/booking-policy', 'Booking, cancellations & refunds'], ['/privacy', 'Privacy policy']]) {
    await phone.goto(origin + path)
    await visible(phone.getByRole('heading', { level: 1, name: heading, exact: true }))
    await noOverflow(phone, 'Mobile policy ' + path)
    await capture(phone, path.slice(1))
  }
  console.log('PASS — checkout displays policy links before payment; both policy pages work at phone width')
}
